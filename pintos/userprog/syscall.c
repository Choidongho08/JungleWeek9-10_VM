bool
sys_create (const char *file_name, unsigned initial_size) { // 파일생성
	lock_acquire();//FD
	bool success = filesys_create (file_name, initial_size);

	lock_release();//FD
	return success;
}

bool
sys_remove (const char *file_name) { //
	lock_acquire();//FD
	bool success = filesys_remove (file_name);

	lock_release();//FD
	return success;
}

